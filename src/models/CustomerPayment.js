import mongoose from 'mongoose';
import {
  PAYMENT_STATUS,
  PAYMENT_STATUS_LIST,
  PAYMENT_TYPE,
  PAYMENT_TYPE_LIST,
  PAYMENT_MODE,
  PAYMENT_MODE_LIST,
} from '../config/constants.js';

const { Schema } = mongoose;

const money = { type: Number, min: 0, set: (v) => Math.round(v * 100) / 100 };

/*
  A payment from the customer to the company.
  It counts toward "received" ONLY when status = 'confirmed'.
  Pending, rejected and cancelled entries are never added to totals.
*/
const customerPaymentSchema = new Schema(
  {
    project: { type: Schema.Types.ObjectId, ref: 'Project', required: true },
    customer: { type: Schema.Types.ObjectId, ref: 'User', required: true },

    type: { type: String, enum: PAYMENT_TYPE_LIST, default: PAYMENT_TYPE.INSTALMENT },
    amount: { ...money, required: true, min: 0.01 },
    mode: { type: String, enum: PAYMENT_MODE_LIST, required: true },
    paymentDate: { type: Date, required: true },

    // UPI transaction ID, cheque number, bank reference, etc.
    reference: { type: String, trim: true, maxlength: 80 },
    notes: { type: String, trim: true, maxlength: 500 },

    status: { type: String, enum: PAYMENT_STATUS_LIST, default: PAYMENT_STATUS.PENDING },

    recordedBy: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    confirmedBy: { type: Schema.Types.ObjectId, ref: 'User' },
    confirmedAt: Date,
    rejectedBy: { type: Schema.Types.ObjectId, ref: 'User' },
    rejectedAt: Date,
    rejectionReason: { type: String, trim: true, maxlength: 300 },
    cancelledBy: { type: Schema.Types.ObjectId, ref: 'User' },
    cancelledAt: Date,
    cancelReason: { type: String, trim: true, maxlength: 300 },

    // Generated by the server when the payment is confirmed (e.g. RCPT-2026-00012)
    receiptNumber: { type: String, trim: true },
    // Optional proof (bank slip or cheque photo) stored in Cloudinary
    proof: {
      publicId: String,
      secureUrl: String,
    },
  },
  { timestamps: true }
);

customerPaymentSchema.pre('validate', function (next) {
  if (this.status === PAYMENT_STATUS.CONFIRMED) {
    if (!this.confirmedBy) this.invalidate('confirmedBy', 'confirmedBy is required');
    if (!this.confirmedAt) this.confirmedAt = new Date();
  }
  if (this.status === PAYMENT_STATUS.REJECTED && !this.rejectionReason) {
    this.invalidate('rejectionReason', 'A reason is required to reject a payment');
  }
  if (this.status === PAYMENT_STATUS.CANCELLED && !this.cancelReason) {
    this.invalidate('cancelReason', 'A reason is required to cancel a payment');
  }
  next();
});

// Once confirmed, the money fields are locked. A mistake is fixed by cancelling
// with a reason and recording a new payment. Always use doc.save(), not
// findOneAndUpdate, so this check runs.
const LOCKED = ['project', 'customer', 'amount', 'mode', 'paymentDate', 'reference', 'type'];
customerPaymentSchema.pre('save', function (next) {
  if (this.isNew) return next();
  const wasConfirmed = this.$__.priorStatus === PAYMENT_STATUS.CONFIRMED;
  const changed = LOCKED.filter((f) => this.isModified(f));
  if (wasConfirmed && changed.length) {
    return next(new Error(`Confirmed payments cannot be edited (${changed.join(', ')}).`));
  }
  next();
});
customerPaymentSchema.post('init', function () {
  this.$__.priorStatus = this.status;
});

customerPaymentSchema.index({ project: 1, status: 1, paymentDate: -1 });
customerPaymentSchema.index({ customer: 1, status: 1, paymentDate: -1 });
customerPaymentSchema.index({ status: 1, createdAt: -1 }); // admin pending queue
customerPaymentSchema.index(
  { receiptNumber: 1 },
  { unique: true, partialFilterExpression: { receiptNumber: { $type: 'string' } } }
);
// Same bank/UPI reference cannot be entered twice for one project
customerPaymentSchema.index(
  { project: 1, reference: 1 },
  {
    unique: true,
    partialFilterExpression: {
      reference: { $type: 'string' },
      status: { $in: [PAYMENT_STATUS.PENDING, PAYMENT_STATUS.CONFIRMED] },
    },
  }
);

customerPaymentSchema.set('toJSON', {
  transform: (_doc, ret) => {
    delete ret.__v;
    return ret;
  },
});

export default mongoose.model('CustomerPayment', customerPaymentSchema);